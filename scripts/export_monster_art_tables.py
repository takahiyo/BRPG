def build_tables():
    manifest = json.loads((ART / "manifest.json").read_text(encoding="utf-8"))
    layout = manifest["layout"]
    assert layout["columns"] == 5 and layout["rows"] == 6
    assert layout["width"] == layout["columns"] * layout["cell"]
    assert layout["height"] == layout["rows"] * layout["cell"]
    size = f"{layout['width']}×{layout['height']}px、1セル{layout['cell']}px"
    margin = (layout["cell"] * 8 + 99) // 100
    catalog = build_catalog()["monsters"]
    program = """const fs=require('fs'),vm=require('vm'),c=vm.createContext({});
for(const f of ['data.js','world-data.js'])vm.runInContext(fs.readFileSync(f,'utf8'),c);
console.log(vm.runInContext('JSON.stringify([...DATA.enemies,...Object.values(DATA.bosses)])',c));"""
    raw = subprocess.check_output(["node", "-e", program], cwd=ROOT)
    enemies = {enemy["id"]: enemy for enemy in json.loads(raw.decode("utf-8"))}
    assert len(catalog) == 400 and len(enemies) == 70
    assert set(ENCOUNTER_VISUALS) == set(enemies), "Missing encounter illustration guidance"
    assert set(ENCOUNTER_FLAVORS) == set(enemies), "Missing encounter flavor"
    entries = manifest["batches"]
    assert {e["id"] for e in entries} == set(catalog) | set(enemies)
    assert len(entries) == len(catalog) + len(enemies), "Duplicate manifest IDs"
    sheets = {}
    for entry in entries:
        sheets.setdefault(entry["sheet"], []).append(entry)
    outputs = {}
    index = ["---", "タグ: [創作]", "---", "", "# モンスター画像制作表・フレーバー索引", "",
             "現行ゲームへの画像追加は遭遇敵の encounter-01〜03 を先に制作。図鑑400種は catalog-01〜14。両者は別IDであり、似た名前でも画像を流用しない。", "",
             f"各リンク先の表を1シートずつ画像生成へ渡す。5列×6行、基準{size}、左上から右へ配置。番号・文字・枠・背景・接地影は描かず、実アルファ透明PNGで出力する。未使用枠は透明。", "",
             "参考：[30体のモンスター透過スプライトアトラス.png](30体のモンスター透過スプライトアトラス.png)。今回の出力実績を基準にした寸法で、サービス全体の固定上限ではない。サンプルの個体を複製せず、今回の対象表を優先。", "",
             "フレーバー中の建物・景色・小物は生態を理解する参考で、背景を描く指示ではない。外見補助は制作用の案であり、対象名・既存特性を優先する。未確定の色・首の本数・装備は生成前に決める。", "",
             "制作規約は [MONSTER_ART_SPEC.md](MONSTER_ART_SPEC.md)。対応表 manifest.json のID・名前・シート・枠は変更していない。参考サンプルは受領済みだが、各セルのゲーム用照合・承認は未実施。", "",
             "| 優先 | シート | 対象数 | 先頭 | 末尾 |", "| --- | --- | --- | --- | --- |"]
    for sheet, batch in sorted(sheets.items(), key=lambda pair: (not pair[0].startswith("encounter"), pair[0])):
        assert [e["cell"] for e in batch] == list(range(1, len(batch) + 1))
        lines = ["---", "タグ: [創作]", "---", "", f"# {sheet} 制作リスト", "",
                 "制作規約は [MONSTER_ART_SPEC.md](../MONSTER_ART_SPEC.md)。左上から入力順、5列×6行。背景は実アルファ透明、文字・番号・枠・接地影なし。名称は画像外のUIで表示。", "",
                 f"基準{size}。サンプルは画風と配置の参考のみで、対象と順序は下表を優先。各セル四辺8%以上（{layout['cell']}pxセルでは{margin}px以上）を透明にし、角・翼・武器も枠内へ収める。", "",
                 "フレーバーは生態・雰囲気の参考。そこに書かれた風景や建物は背景へ描かない。外見補助は制作案で、名称と既存特性が優先。", "",
                 "| 枠 | 行 | 列 | ゲームID | 対象名（厳守） | 種族・特性/外見補助 | 生態・生息地 | フレーバーテキスト |",
                 "| --- | --- | --- | --- | --- | --- | --- | --- |"]
        for entry in batch:
            mid, cell = entry["id"], entry["cell"]
            source = catalog.get(mid) or enemies[mid]
            assert source["name"] == entry["name"], f"Name mismatch: {mid}"
            if mid in catalog:
                visual = source["category"] + " / " + "・".join(source["traits"])
                ecology, flavor = source["ecology"], source["flavor"]
            else:
                visual = source["desc"] + " 制作補助：" + ENCOUNTER_VISUALS[mid]
                ecology, flavor = source["habitat"], ENCOUNTER_FLAVORS[mid]
            values = [cell, (cell - 1) // 5 + 1, (cell - 1) % 5 + 1, mid, source["name"], visual, ecology, flavor]
            lines.append("| " + " | ".join(str(v).replace("|", "&#124;").replace("\n", " ") for v in values) + " |")
        if len(batch) < 30:
            lines += ["", f"枠{len(batch) + 1}〜30は透明の空白。"]
        lines += ["", "原資料：図鑑はモンスター辞典と既存モンスターフレーバー、遭遇敵はworld-data.jsの名称・生息地・説明。遭遇敵の外見補助とフレーバーは画像制作用の創作案で、ゲーム数値や設定を変更するものではない。", ""]
        outputs[ART / f"{sheet}.md"] = "\n".join(lines)
        priority = "先行（ゲーム実装用）" if sheet.startswith("encounter") else "図鑑用"
        index.append(f"| {priority} | [{sheet}](monster-art/{sheet}.md) | {len(batch)} | {batch[0]['name']} | {batch[-1]['name']} |")
    index += ["", "## 再生成", "", "`python scripts/export_monster_art_tables.py`（Python 3・Node.js、追加パッケージ不要）。既存manifestを読み取り、17シートとこの索引を再出力する。", ""]
    outputs[ROOT / "docs/MONSTER_ART_TABLES.md"] = "\n".join(index)
    return outputs


if __name__ == "__main__":
    outputs = build_tables()
    for file, content in outputs.items():
        file.write_text(content, encoding="utf-8")
    print("Generated 17 sheets + index: 400 catalog monsters, 70 encounter monsters; manifest unchanged.")
